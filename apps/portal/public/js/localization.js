  function formatCurrencyAmount(usdAmount, targetCurrCode) {
    const curr = CURRENCIES[targetCurrCode] || CURRENCIES.KES;
    const raw = usdAmount * curr.usdRate;
    let formattedNum;
    if (curr.code === 'USD' || curr.code === 'GBP' || curr.code === 'EUR') {
      if (Number.isInteger(usdAmount) || raw >= 100) {
        formattedNum = Math.round(raw).toLocaleString('en-US');
      } else {
        formattedNum = raw.toFixed(2);
      }
      return curr.symbol + formattedNum;
    } else {
      const rounded = raw < 10 ? raw.toFixed(2) : Math.round(raw).toLocaleString('en-US');
      return curr.symbol + ' ' + rounded;
    }
  }

  function convertCurrencyInText(text, targetCurrCode, lang) {
    if (!text) return text;
    let result = text;

    // 1. If target currency is NOT USD, convert inline $X amounts (e.g., $1,500, $9.99, $0.99, $400 Million)
    if (targetCurrCode !== 'USD' && result.includes('$')) {
      result = result.replace(/\$\s*(\d{1,3}(?:,\d{3})*(?:\.\d{1,2})?|\d+(?:\.\d{1,2})?)(\s*(?:Million|Billion|Milioni|Bilioni|M|B|k|K))?(?:\s*USD)?/g, (match, numStr, scaleStr) => {
        const cleanNum = parseFloat(numStr.replace(/,/g, ''));
        if (isNaN(cleanNum)) return match;
        const curr = CURRENCIES[targetCurrCode] || CURRENCIES.KES;
        if (scaleStr) {
          const scaledVal = Math.round(cleanNum * curr.usdRate * 10) / 10;
          let scaleWord = scaleStr.trim();
          if (lang === 'sw') {
            if (/million/i.test(scaleWord)) scaleWord = 'Milioni';
            if (/billion/i.test(scaleWord)) scaleWord = 'Bilioni';
          }
          return curr.symbol + ' ' + scaledVal.toLocaleString('en-US') + ' ' + scaleWord;
        }
        return formatCurrencyAmount(cleanNum, targetCurrCode);
      });
    }

    // 2. If target currency is NOT KES, convert inline KES X / KSh X amounts
    if (targetCurrCode !== 'KES' && (/\b(?:KES|KSh)\s*\d/i.test(result))) {
      result = result.replace(/\b(?:KES|KSh)\s*(\d{1,3}(?:,\d{3})*(?:\.\d{1,2})?|\d+(?:\.\d{1,2})?)/gi, (match, numStr) => {
        const cleanKes = parseFloat(numStr.replace(/,/g, ''));
        if (isNaN(cleanKes)) return match;
        const usdEquiv = cleanKes / 130.0;
        return formatCurrencyAmount(usdEquiv, targetCurrCode);
      });
    }

    return result;
  }

